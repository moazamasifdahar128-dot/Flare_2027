export type Copy = { [K in keyof typeof copy]: string };

const Ctx = createContext<{ t: Copy; lang: LangId; setLang: (lang: LangId) => void }>({
  t: copy,
  lang: "en",
  setLang: () => undefined,
});

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangId>("en");
  useEffect(() => {
    const saved = window.localStorage.getItem("flare.lang") as LangId | null;
    if (saved && saved in packs) setLangState(saved);
  }, []);
  function setLang(next: LangId) {
    setLangState(next);
    window.localStorage.setItem("flare.lang", next);
    document.documentElement.lang = next;
    document.documentElement.dir = next === "ur" || next === "ar" ? "rtl" : "ltr";
  }
  const t = { ...copy, ...packs[lang] };
  return <Ctx.Provider value={{ t, lang, setLang }}>{children}</Ctx.Provider>;
}

export function useI18n() {
  return useContext(Ctx);
}

